public class TakeAndChargeMain {

    private Form current;
    private Resources baseTheme;


    public void init(Object context) {
        // use two network threads instead of one
        updateNetworkThreadCount(2);

        UIManager.initFirstTheme("/theme");
        try {
            baseTheme = Resources.openLayered("/baseTheme");
        } catch (IOException e) {
            Log.e(e);
        }

        Toolbar.setGlobalToolbar(true);
        if (!isTablet()) {
            Toolbar.setOnTopSideMenu(true);
        }
        Dialog.setDefaultBlurBackgroundRadius(10);


//        Label.setDefaultGap(convertToPixels(2));
        // only portrait mode
        Display.getInstance().lockOrientation(true);
        Display.getInstance().setEnableAsyncStackTraces(true);

        // Pro only feature
        Log.bindCrashProtection(true);
        loadLocalization();

        addNetworkErrorListener(err -> {
            // prevent the event from propagating
            err.consume();
            FullScreenLoader.stop();
            if (err.getError() != null) {
                Log.e(err.getError());
            }
            Log.sendLogAsync();
            if (!Connectivity.isConnected()) {
                if (MainForm.get().isVisible()) {
                    MainForm.get().getBottomPanel().showError("No Internet connection");
                } else
                    Dialog.show("No Internet connection", "Please check your Internet connection and try again", "OK", null);
            } else {
                if (err.getResponseCode() == 0) {
                    if (MainForm.get().isVisible()) {
                        MainForm.get().getBottomPanel().showError("No connection with server");
                    }
                } else
                    Dialog.show("Connection Error " + err.getResponseCode(),
                            err.getError() + " while connecting to " + err.getConnectionRequest().getUrl(),
                            "OK", null);
            }
        });
    }

    private void loadLocalization() {
        String local = L10NManager.getInstance().getLanguage();
        Hashtable<String, String> localizationBundle = baseTheme.getL10N("prime", local);
        UIManager.getInstance().setBundle(localizationBundle);
    }

    public void start() {
        if (current != null) {
            current.show();
        } else {
            new SplashScreen().show();
//            MainForm.get().show();
//            new RegisterMobileNumberStep1().show();
        }
        MainForm.appInit();
    }

    public void stop() {
        current = getCurrentForm();
        if (current instanceof Dialog) {
            ((Dialog) current).dispose();
            current = getCurrentForm();
        }
        MainForm.get().appClose();
    }

    public void destroy() {
        MainForm.get().appClose();
    }

}
